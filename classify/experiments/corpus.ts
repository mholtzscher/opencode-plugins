export const readCorpusSource = async (entry: CorpusCase) => {
  const source = await readFile(entry.path, "utf-8");
  if (
    createHash("sha256").update(source).digest("hex") !==
    reviewedHashes.get(path.basename(entry.path))
  ) {
    throw new Error(
      `Corpus changed: review ranges and labels before updating the hash for ${entry.path}`
    );
  }
  return source;
};
